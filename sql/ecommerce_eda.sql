-- 1. Dimensions Exploration: Customers & Products

--Explore Customer Countries
SELECT
  DISTINCT country
FROM
  dim_customers
;

--Explore Product Categories & Hierarchy
SELECT
  DISTINCT category, 
  subcategory,
  product_name
FROM
  dim_products
ORDER BY
  category, subcategory
;


-- 2. Date & Time Exploration

-- Find the date of the first and last order?
-- How many years of sales are available?
SELECT
  MIN(order_date) AS first_order_date,
  MAX(order_date) AS last_order_date,
  DATE_PART('year', AGE(MAX(order_date), MIN(order_date))) AS order_range_years
FROM 
  fact_sales
;

--Find the youngest and oldest customer
SELECT
  MIN(birthdate) AS oldest_birthdate,
  DATE_PART('year', AGE(NOW(), MIN(birthdate))) AS oldest_age,
  MAX(birthdate) AS youngest_birthdate,
  DATE_PART('year', AGE(NOW(), MAX(birthdate))) AS youngest_age
FROM
  dim_customers
;


