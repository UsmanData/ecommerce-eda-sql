-- A consolidated KPI query was also created using UNION ALL to produce a single metrics report, suitable for dashboards and executive summaries.
SELECT 'Total Sales' AS measure_name, SUM(sales_amount) AS measure_value FROM fact_sales
UNION ALL
SELECT 'Total Quantity', SUM(quantity) FROM fact_sales
UNION ALL
SELECT 'Average Price', ROUND(AVG(price), 2) FROM fact_sales
UNION ALL
SELECT 'Total No. Orders', COUNT(DISTINCT order_number) FROM fact_sales
UNION ALL
SELECT 'Total No. Products', COUNT(DISTINCT product_name) FROM dim_products
UNION ALL
SELECT 'Total No. Customers', COUNT(DISTINCT customer_key) FROM dim_customers
;


-- 4. Magnitude Analysis (Category-Level Comparisons)

-- Find total customers by countries
SELECT
  country,
  COUNT(customer_key) AS total_customers
FROM
  dim_customers
GROUP BY
  country
ORDER BY
  total_customers DESC
;

-- Find the total customers by gender
SELECT
  gender,
  COUNT(customer_key) AS total_customers
FROM
  dim_customers
GROUP BY
  gender
ORDER BY
  total_customers DESC
;

-- Find total products by category
SELECT
  category,
  COUNT(product_key) AS total_products
FROM
  dim_products
GROUP BY
  category
ORDER BY
  total_products DESC
;

-- What is the average costs in each category?
SELECT
  category,
  ROUND(AVG(cost), 2) AS avg_cost
FROM
  dim_products
GROUP BY
  category
ORDER BY
  avg_cost DESC
;

-- What is the total revenue generated for each category?
SELECT
  p.category,
  SUM(f.sales_amount) AS total_revenue
FROM
  fact_sales AS f
LEFT JOIN dim_products AS p
  ON f.product_key = p.product_key
GROUP BY
  p.category
ORDER BY
  total_revenue DESC
;

-- What is the total revenue generated by top 50 customer?
SELECT
  c.customer_key,
  c.first_name,
  c.last_name,
  SUM(f.sales_amount) AS total_revenue
FROM
  fact_sales AS f
LEFT JOIN dim_customers AS c
  ON f.customer_key = c.customer_key
GROUP BY
  c.customer_key,
  c.first_name,
  c.last_name
ORDER BY
  total_revenue DESC
LIMIT 50
;

-- What is the distribution of items sold across countries?
 SELECT
  c.country,
  SUM(f.quantity) AS total_sold_items
FROM
  fact_sales AS f
LEFT JOIN dim_customers AS c
  ON f.customer_key = c.customer_key
GROUP BY
  c.country
ORDER BY
  total_sold_items DESC
;


-- 5. Ranking Analysis (Top & Bottom Performers)

-- Which 5 Products generate the highest revenue?
SELECT
  p.product_name,
  SUM(f.sales_amount) AS total_revenue,
  ROW_NUMBER() OVER(ORDER BY SUM(f.sales_amount) DESC) AS rank_products
FROM
  fact_sales AS f
LEFT JOIN dim_products AS p
  ON f.product_key = p.product_key
GROUP BY
  p.product_name
LIMIT 5
;

-- What are the 5 worst-performing products in terms of sales?
SELECT
  p.product_name,
  SUM(f.sales_amount) AS total_revenue,
  ROW_NUMBER() OVER(ORDER BY SUM(f.sales_amount) ASC) AS rank_products
FROM
  fact_sales AS f
LEFT JOIN dim_products AS p
  ON f.product_key = p.product_key
GROUP BY
  p.product_name
LIMIT 5
;

-- Find the Top-10 customers who have generated the highest revenue?  
SELECT
  c.customer_key,
  c.first_name,
  c.last_name,
  SUM(f.sales_amount) AS total_revenue,
  ROW_NUMBER() OVER(ORDER BY SUM(f.sales_amount) DESC) AS rank_customers
FROM
  fact_sales AS f
LEFT JOIN dim_customers AS c
  ON f.customer_key = c.customer_key
GROUP BY
  c.customer_key,
  c.first_name,
  c.last_name
LIMIT 10
;

-- Find the 3 customers with the fewest orders placed?
SELECT
  c.customer_key,
  c.first_name,
  c.last_name,
  COUNT(f.order_number) AS total_orders,
  ROW_NUMBER() OVER(ORDER BY SUM(f.sales_amount) ASC) AS rank_customers
FROM
  fact_sales AS f
LEFT JOIN dim_customers AS c
  ON f.customer_key = c.customer_key
GROUP BY
  c.customer_key,
  c.first_name,
  c.last_name
LIMIT 3
;

